from harness import H
import sys
ok=[]; bad=[]
def chk(n,c): (ok if c else bad).append(n); print(("PASS " if c else "FAIL ")+n)
W=int(sys.argv[1]); Hh=int(sys.argv[2])
h=H(W,Hh,mobile=W<600); pg=h.pg
h.go("")
pg.evaluate("""()=>{const t=state.jobs.find(j=>j.date===isoToday(0)); t.tenants='Jo Example 07577 488037'; t.notes='Keys from concierge, code 1234. Call agent first on 020 7946 0018'; saveJobs(); render();}""")
pg.wait_for_timeout(200)
tiles=[t.split("\n")[1] for t in pg.locator(".d-tile").all_inner_texts()]; print(tiles)
chk("tile order grouped", tiles==["Reports due","Times to agree","Photos not done","New bookings","Out for signature","Comment windows","Amendments","To invoice","Awaiting payment","On time (7 days)"])
heads=pg.locator(".d-ghead").all_inner_texts(); vis=pg.locator(".d-ghead").first.is_visible(); print(heads, "visible", vis)
chk("group headings shown on wide screens only", vis == (W>1250))
zeros=pg.evaluate("[...document.querySelectorAll('.d-tile.zero')].map(e=>e.innerText.split('\\n')[1])"); print("faded:",zeros)
info=pg.locator(".d-info").first.inner_text(); print("info:",info.replace("\n"," | "))
chk("today shows tenant + notes", "Jo Example" in info and "concierge" in info)
tels=pg.evaluate("[...document.querySelectorAll('.d-info a.d-tel')].map(a=>a.getAttribute('href'))"); print(tels)
chk("phone numbers tap-to-call", tels==["tel:07577488037","tel:02079460018"])
btn=pg.locator(".page-actions button:has-text('Refresh all')")
chk("Refresh all button on dashboard", btn.count()==1)
btn.click(); pg.wait_for_timeout(500)
print("after refresh click:", pg.locator(".page-actions").inner_text().replace("\n"," | "), "| cloud:", pg.evaluate("state.cloudStatus+' '+state.cloudMsg"))
pg.clock.run_for(2000); pg.wait_for_timeout(300)
chk("Refresh all doesn't stick on Refreshing… without Google", "Refreshing" not in pg.locator(".page-actions").inner_text())
pg.locator(".side-nav a:has-text('Job Log')").first.click(); pg.wait_for_timeout(200)
chk("Job Log keeps Check for new bookings", pg.locator(".page-actions button:has-text('Check for new bookings')").count()==1)
pg.locator(".side-nav a:has-text('Dashboard')").first.click(); pg.wait_for_timeout(200)
sw=pg.evaluate("document.documentElement.scrollWidth"); chk("no sideways scroll", sw<=W)
errs=[e for e in h.errors if "ERR_FAILED" not in e]; print("errors",errs); chk("no page errors", not errs)
h.shot("dash12b_%d"%W)
print("PASS",len(ok),"FAIL",len(bad),bad); h.close()
